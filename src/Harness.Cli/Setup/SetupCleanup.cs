using System.Diagnostics;
using System.Text;
using Harness.Core.Instructions;
using Harness.Infrastructure.Clients;
using Harness.Infrastructure.Git;

namespace Harness.Cli.Setup;

internal static class SetupCleanup
{
    internal sealed record Removal(string Path, Func<FileChange> Apply);
    private static readonly MarkedBlock GitBlock = new("# BEGIN harness hook (generated by 'harness hooks'; edit outside this block)", "# END harness hook", "harness hook");
    private static readonly MarkedBlock CompletionBlock = new("# >>> harness completion >>>", "# <<< harness completion <<<", "harness completion");
    public static IEnumerable<Removal> ClientHooks(ClientPaths paths, string? root, bool dryRun)
    {
        List<(string Client, string Path)> targets = [("claude-code", Path.Combine(Environment.GetEnvironmentVariable("CLAUDE_CONFIG_DIR") is { Length: > 0 } dir ? dir : Path.Combine(paths.Home, ".claude"), "settings.json")), ("codex", Path.Combine(Path.GetDirectoryName(paths.CodexFile)!, "hooks.json"))];
        if (root is not null)
        {
            targets.AddRange([("claude-code", Path.Combine(root, ".claude", "settings.json")), ("claude-code", Path.Combine(root, ".claude", "settings.local.json")), ("codex", Path.Combine(root, ".codex", "hooks.json"))]);
        }

        return targets.Select(t => new Removal(t.Path, () => ClientHookCleanup.Remove(t.Path, t.Client, dryRun)));
    }
    public static async Task<IReadOnlyList<Removal>> GitHooksAsync(GitRepository repository, bool dryRun, CancellationToken token)
    {
        var configured = await QueryAsync("git", ["-C", repository.Root, "config", "--get", "core.hooksPath"], token);
        var hooks = configured.Length is 0 ? Path.Combine(repository.CommonDir, "hooks") : Path.GetFullPath(configured, repository.Root);
        return new[] { "post-commit", "post-checkout", "post-merge", "post-rewrite" }.Select(name =>
        {
            var path = Path.Combine(hooks, name);
            return new Removal(path, () => FileEditor.Apply(path, (source, exists) => exists ? GitBlock.Cut(source) : new(source, "absent"), dryRun, empty: source => string.IsNullOrWhiteSpace(source) || source.Trim() is "#!/bin/sh"));
        }).ToArray();
    }
    public static async Task<IReadOnlyList<Removal>> CompletionsAsync(string home, bool dryRun, CancellationToken token)
    {
        var zsh = Environment.GetEnvironmentVariable("ZDOTDIR") is { Length: > 0 } z ? z : home;
        var config = Environment.GetEnvironmentVariable("XDG_CONFIG_HOME") is { Length: > 0 } x ? x : Path.Combine(home, ".config");
        var profile = "";
        // An explicitly redirected Windows home must not resolve the real user's Documents profile.
        var shells = OperatingSystem.IsWindows() && !string.Equals(Path.GetFullPath(home), Path.GetFullPath(Environment.GetFolderPath(Environment.SpecialFolder.UserProfile)), StringComparison.OrdinalIgnoreCase) ? Array.Empty<string>() : ["pwsh", "powershell"];
        foreach (var exe in shells)
        {
            profile = await QueryAsync(exe, ["-NoProfile", "-NonInteractive", "-Command", "$PROFILE.CurrentUserAllHosts"], token);
            if (Path.IsPathRooted(profile))
            {
                break;
            }
        }
        if (!Path.IsPathRooted(profile))
        {
            profile = OperatingSystem.IsWindows() ? Path.Combine(home, "Documents", "PowerShell", "profile.ps1") : Path.Combine(config, "powershell", "profile.ps1");
        }

        List<Removal> changes = [];
        foreach (var path in new[] { Path.Combine(zsh, ".zshrc"), Path.Combine(home, ".bashrc"), profile })
        {
            changes.Add(new(path, () => FileEditor.Apply(path, (source, exists) => exists ? CompletionBlock.Cut(source) : new(source, "absent"), dryRun, backup: true)));
        }

        var fish = Path.Combine(config, "fish", "completions", "harness.fish");
        changes.Add(new(fish, () => FileEditor.Apply(fish, (source, exists) =>
        {
            const string Generated = "complete -c harness -f -a '(harness __complete fish (commandline -opc)[2..-1] (commandline -ct) 2>/dev/null)'";
            var lines = source.Split('\n');
            var kept = lines.Where(line => line.Trim() != Generated).ToArray();
            return exists && kept.Length != lines.Length ? new(string.Join('\n', kept), "remove") : new(source, "absent");
        }, dryRun, backup: true)));
        return changes;
    }
    [System.Diagnostics.CodeAnalysis.SuppressMessage("Security", "S4036:Searching OS commands in PATH is security-sensitive", Justification = "Queries installed Git and shells with fixed arguments and no user command text.")]
    private static async Task<string> QueryAsync(string executable, IReadOnlyList<string> args, CancellationToken token)
    {
        using var deadline = CancellationTokenSource.CreateLinkedTokenSource(token);
        deadline.CancelAfter(TimeSpan.FromSeconds(10));
        using var process = new Process { StartInfo = new(executable) { UseShellExecute = false, RedirectStandardInput = true, RedirectStandardOutput = true, RedirectStandardError = true, CreateNoWindow = true, StandardOutputEncoding = new UTF8Encoding(false, true) } };
        foreach (var arg in args)
        {
            process.StartInfo.ArgumentList.Add(arg);
        }

        var started = false;
        try
        {
            process.Start();
            started = true;
            process.StandardInput.Close();
            var stdout = process.StandardOutput.ReadToEndAsync(deadline.Token);
            var stderr = process.StandardError.ReadToEndAsync(deadline.Token);
            await process.WaitForExitAsync(deadline.Token);
            await stderr;
            return process.ExitCode is 0 ? (await stdout).Trim() : "";
        }
        catch (System.ComponentModel.Win32Exception) { return ""; }
        catch (OperationCanceledException) when (!token.IsCancellationRequested)
        {
            return "";
        }
        finally
        {
            if (started && !process.HasExited)
            {
                process.Kill(entireProcessTree: true);
                await process.WaitForExitAsync(CancellationToken.None);
            }
        }
    }
}
