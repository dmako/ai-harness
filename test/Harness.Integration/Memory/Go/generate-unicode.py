"""Generate portable Go Unicode semantics from `memory-oracle unicode unused` JSON."""
import argparse
import json
from pathlib import Path

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("input", type=Path)
parser.add_argument("--output", type=Path, default=Path("src/Harness.Core/Memory/GoUnicode.cs"))
args = parser.parse_args()
data = json.loads(args.input.read_text(encoding="utf-8-sig"))
assert data["version"] == "17.0.0"
mapping = sorted((ord(key), ord(value) - ord(key)) for key, value in data["lower"].items())
ranges = []
index = 0
while index < len(mapping):
    first, delta = mapping[index]
    last = first
    stride = 1
    if index + 1 < len(mapping) and mapping[index + 1][1] == delta:
        stride = mapping[index + 1][0] - first
    if stride not in (1, 2):
        stride = 1
    index += 1
    while index < len(mapping) and mapping[index] == (last + stride, delta):
        last = mapping[index][0]
        index += 1
    ranges.append((first, last, stride, delta))

lines = [
    "// Generated by test/Harness.Integration/Memory/Go/generate-unicode.py.",
    "// Go 1.27.1 unicode 17.0.0, frozen oracle 9cb401dd2de4. See LICENSE.txt.",
    "using System.Text;", "", "namespace Harness.Core.Memory;", "", "internal static class GoUnicode", "{",
    "    private static readonly (int First, int Last, int Stride, int Delta)[] LowerRanges =", "    [",
]
lines += [f"        (0x{first:X}, 0x{last:X}, {stride}, {delta})," for first, last, stride, delta in ranges]
lines += ["    ];", "", "    private static readonly (int First, int Last)[] WordRanges =", "    ["]
lines += [f"        (0x{first:X}, 0x{last:X})," for first, last in data["word_ranges"]]
lines += ["    ];", "", "    public static Rune ToLower(Rune rune)", "    {",
    "        var scalar = rune.Value;", "        var low = 0;", "        var high = LowerRanges.Length - 1;",
    "        while (low <= high)", "        {", "            var middle = low + ((high - low) / 2);",
    "            var range = LowerRanges[middle];", "            if (scalar < range.First) high = middle - 1;",
    "            else if (scalar > range.Last) low = middle + 1;",
    "            else return (scalar - range.First) % range.Stride is 0 ? new Rune(scalar + range.Delta) : rune;",
    "        }", "", "        return rune;", "    }", "",
    "    public static bool IsLetterOrDigit(Rune rune)", "    {", "        var scalar = rune.Value;",
    "        var low = 0;", "        var high = WordRanges.Length - 1;", "        while (low <= high)", "        {",
    "            var middle = low + ((high - low) / 2);", "            var range = WordRanges[middle];",
    "            if (scalar < range.First) high = middle - 1;", "            else if (scalar > range.Last) low = middle + 1;",
    "            else return true;", "        }", "", "        return false;", "    }", "}",
]
with args.output.open("w", encoding="utf-8", newline="\r\n") as output:
    output.write("\n".join(lines) + "\n")
print(f"{len(mapping)} lower mappings, {len(ranges)} case ranges, {len(data['word_ranges'])} word ranges")
